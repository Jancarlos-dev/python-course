# arithmetic operators
# los operadores aritmeticos sirven para hacer operaciones matematicas


# suma (+)
# sirve para sumar dos numeros

suma = 12 + 5

print(suma)

# resultado: 17


# resta (-)
# sirve para restar un numero de otro

resta = 12 - 5

print(resta)

# resultado: 7


# multiplicacion (*)
# sirve para multiplicar dos numeros

multiplicacion = 12 * 5

print(multiplicacion)

# resultado: 60


# division (/)
# sirve para dividir dos numeros
# la division normalmente devuelve un numero con decimales

division = 12 / 5

print(division)

# resultado: 2.4


# exponente (**)
# sirve para elevar un numero a una potencia

exponente = 12 ** 5

print(exponente)

# 12 elevado a la 5


# division entera (//)
# divide los numeros pero se queda solamente con la parte entera
# no toma en cuenta los decimales

division_baja = 12 // 5

print(division_baja)

# resultado: 2


# modulo o resto (%)
# muestra el resto que queda despues de una division

resto = 12 % 5

print(resto)

# resultado: 2
# porque 12 dividido entre 5 da 2 y sobra 2


# ejemplo usando varias operaciones

numero1 = 10
numero2 = 3

print(numero1 + numero2)  # suma
print(numero1 - numero2)  # resta
print(numero1 * numero2)  # multiplicacion
print(numero1 / numero2)  # division
print(numero1 // numero2) # division entera
print(numero1 % numero2)  # resto
print(numero1 ** numero2) # exponente